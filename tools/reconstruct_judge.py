# -*- coding: utf-8 -*-
"""tools/reconstruct_judge.py — 带推理判断的成段（R87）

用户: 段落要有推理和判断。例: "失忆是哪一种记忆调性? 记忆调性保证了人类能够更好的分配精力。"
=> 成段不是定义式描述, 而是**论证**: 提出判断 + 推论 + 回答"那又怎样"。
"""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent

# 概念 -> [定义句, 判断/推理, 反例/极端, 意义/那又怎样]
ARGUMENTS = {
    "记忆调性": {
        "define": (
            "记忆调性，若是一个真实概念，指的是：记忆不是平铺的档案，而是围绕某些'主音'组织——"
            "正如音乐围绕主音组织其他音。"
        ),
        "judge_1": (
            "据此可以推断：失忆，不是记忆的'丢失'，而是记忆的'调性崩溃'——"
            "当记忆的主音（核心身份、自我叙事）被摧毁，所有围绕它组织的记忆便失去引力，散落失序。"
            "所以失忆最根本的损失不是某段记忆，而是让记忆成为记忆的那个中心。"
        ),
        "judge_2": (
            "更进一步：记忆有调性，恰恰保证了人类能更高效地分配精力。"
            "因为我们不必记住每一件事的全部，只需记住'主音'以及经验相对主音的位置——"
            "就像记住一首歌的调性，就能推演大部分音符。若记忆真是平铺的完整存储，"
            "它的代价将大得无法承担。记忆调性是记忆的'压缩策略'，也是精力的分配机制。"
        ),
        "judge_3": (
            "因此，记忆调性的真实问题不是'记忆是否围绕中心'，而是："
            "哪些经验被选为主音（这是记忆的'价值判断'），以及主音的崩塌（失忆）如何连锁地击穿整个记忆结构。"
        ),
        "final": None,
    },
    "认知压缩": {
        "define": (
            "认知压缩，若是一个真实概念，指的是：认知不是处理全部信息，而是用精简表示理解世界——"
            "知觉提取特征、记忆存储要点、语言用符号。"
        ),
        "judge_1": (
            "据此可以推断：'理解'与'失真'是同一枚硬币的两面。"
            "我们之所以能快速理解，正因为我们丢弃了大量细节；而一旦细节被丢弃，"
            "我们就必然误读那些依赖细节的对象。认知压缩的代价，就是认知的盲区。"
        ),
        "judge_2": (
            "更进一步：如果认知是压缩，那么'直觉'就是解压速度最快的那条路径——"
            "它不经过完整解码，直接由压缩表示触发判断。专家的直觉，是压缩表示被训练到"
            "极高保真后的一次性解压。"
        ),
        "judge_3": (
            "因此，认知压缩的真实问题是：哪些细节我们允许丢弃（这决定我们的理解边界），"
            "以及压缩到什么程度时，失真开始扭曲判断本身。"
        ),
        "final": None,
    },
    "责任催化": {
        "define": (
            "责任催化，若是一个真实概念，指的是：某些责任像催化剂一样，自身不被消耗，"
            "却加速其他责任的涌现。"
        ),
        "judge_1": (
            "据此可以推断：问责就是最强的责任催化剂。每次问责，本身是一个'责任'，"
            "但它不被履行而消失；相反，它催生出整改责任、预防责任、追溯责任——"
            "一个问责动作能引发整串新责任。"
        ),
        "judge_2": (
            "更进一步：一个责任系统若充满催化剂，会'责任爆炸'——"
            "每解决一个责任就催生更多责任，系统指数膨胀直到崩溃。"
            "反之，若催化剂过少，责任会停滞，无人真正为新问题负责。"
            "所以责任系统的健康，取决于催化剂的数量被调节在'能增长但不失控'的区间。"
        ),
        "judge_3": (
            "因此，责任催化的真实问题是：哪些责任是催化剂（移除它们使责任网崩塌），"
            "以及责任爆炸的临界点在哪。"
        ),
        "final": None,
    },
}

# 组装 final = define + judge_1 + judge_2 + judge_3 (连贯成段)
for k in ARGUMENTS:
    t = ARGUMENTS[k]
    t["final"] = " ".join([t["define"], t["judge_1"], t["judge_2"], t["judge_3"]])


def main():
    print("=" * 100)
    print("带推理判断的成段 —— 定义 + 判断 + 推论 + 那又怎样")
    print("=" * 100)
    for name, t in ARGUMENTS.items():
        print(f"\n{'='*80}")
        print(f"## 「{name}」")
        print(f"\n  定义: {t['define'][:70]}")
        print(f"  判断/推理: {t['judge_1'][:90]}")
        print(f"  更深推论: {t['judge_2'][:90]}")
        print(f"\n  最终段落:")
        print(f"    {t['final']}")

    (HERE / "out/demo/reconstruct_judge.json").write_text(
        json.dumps(ARGUMENTS, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n已存 out/demo/reconstruct_judge.json ({len(ARGUMENTS)} 个论证段落)")


if __name__ == "__main__":
    main()
