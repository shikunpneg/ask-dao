def bridge(obj, method):
    """对象与方法的**结构桥梁**: 共享的结构类型。空集 = 无理由的配对。"""
    return OBJ_STRUCT.get(obj, set()) & METHOD_STRUCT.get(method, set())


def fusion_spec(a, b):
    """F_a ⊗ F_b = 用 b 的方法盯 a 的对象（非对称）。"""
    Oa, Ma, Qa, Ja, Ga = FIELDS[a]
    Ob, Mb, Qb, Jb, Gb = FIELDS[b]
    # 融合领域: 对象取自 a, 方法取自 b
    return {
        "shape": f"{a}的对象 × {b}的方法",
        "name": f"计算{a}学({b}方法)" if Ga != Gb else f"{b}式{a}研究",
        "objects": Oa, "methods": Mb,
        "parent_questions": [Qa, Qb],
        "new_question": f"用{b}的方法, {a}的对象会呈现什么{a}自己问不出的性质?",
        "judge": Jb if Gb in ("数学系", "工程/信息", "自然科学") else Ja,
        "groups": (Ga, Gb),
        "cross": Ga != Gb,
    }


