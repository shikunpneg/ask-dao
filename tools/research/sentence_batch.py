def render(name, d):
    print(f"\n{'='*84}")
    print(f"## 「{name}」")
    print(f"  ① 问: {d['q']}")
    print(f"  ② 拆实体:")
    for e in d["entities"]:
        print(f"     - {e['name']}")
    print(f"  ③ 再问:")
    for e in d["entities"]:
        print(f"     - {e['q']} -> {e['ess']}")
    print(f"  ④ 再拆:")
    for e in d["entities"]:
        print(f"     - {e['name']}: {' / '.join(e['sub'])}")
    print(f"  ⑤ 成段:")
    print(f"     {d['para']}")


def main():
    print("=" * 100)
    print("批量造句(用户方法) —— 问→拆→再问→再拆→成段")
    print("=" * 100)
    print(f"  批量: {len(BATCH)} 个概念")
    for name, d in BATCH.items():
        render(name, d)
    (HERE / "out/demo/sentence_batch.json").write_text(
        json.dumps(BATCH, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n已存 out/demo/sentence_batch.json ({len(BATCH)} 个段落理解)")


if __name__ == "__main__":
    main()
