def interpret(a, b, wa, wb):
    """给 a×b 一个有想象力的诠释(模板化的'理解')。"""
    (da, sa, ma), (db, sb, mb) = wa, wb
    base = f"{a}{b}"
    cands = []
    # 模板1: 机制类比(a 像 b 一样运作)
    cands.append(f"「{base}」 = {a}像{ma}一样{mb}, 即{a}被组织成{b}式的运作")
    # 模板2: 结构迁移(b 的结构搬到 a)
    shared = set(sa) & set(sb)
    if shared:
        cands.append(f"「{base}」 = 把{b}的{mb}结构迁移到{a}上, 使{a}获得{mb}的能力")
    else:
        cands.append(f"「{base}」 = 迫使{a}在{b}的约束/判据下运作(跨域张力)")
    # 模板3: 涌现(a×b 是单独没有的)
    cands.append(f"「{base}」 = {a}与{b}相遇时涌现的、两者单独都没有的新性质")
    return cands


def link(a, b):
    return f"在{b}的操作下, {a}会呈现什么单看{a}或单看{b}问不出的性质?"


def main():
    words = list(WORDS)
    print("=" * 100)
