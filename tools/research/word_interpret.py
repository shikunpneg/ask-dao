    print("=" * 100)
    print(f"  词数: {len(words)}  组合: {len(words)**2}")

    all_int = []
    for a in words:
        for b in words:
            if a == b:
                continue
            term = a + b
            cands = interpret(a, b, WORDS[a], WORDS[b])
            all_int.append({"term": term, "a": a, "b": b,
                            "domain": f"{WORDS[a][0]}×{WORDS[b][0]}",
                            "interpretations": cands,
                            "link": link(a, b)})

    print(f"  全部 {len(all_int)} 个组合词都有诠释")
    print(f"\n  == 样本(你的'文学工业化'类型 + 其它) ==")
    # 挑几个: 含"工业化"、"催化"、"编码" 的组合
    picks = [x for x in all_int if any(k in x["term"] for k in ("工业化", "催化", "编码", "记忆", "责任", "熵", "测度"))]
    # 选 8 个有代表性的
    for x in picks[:8]:
        print(f"\n  ▸ 「{x['term']}」  ({x['domain']})")
