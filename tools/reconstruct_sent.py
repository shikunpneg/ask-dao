# -*- coding: utf-8 -*-
"""tools/reconstruct_sent.py — 句子化还原: 拆到底 -> 用完整句子从底还原 -> 成有语义的段落（R86）

用户: 括号嵌套拼凑不成有语义的段落, 尝试嵌套或者其他。
=> 放弃括号嵌套, 每层用**自然语言完整句子**表达, 原子概念融入句子。
"""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent

# 概念树: 每节点带 "sentence"(该节点的完整句子, 由子的句子组合)
# 还原 = 父节点的句子 = 用子句子的内容织成一个通顺的新句
TREE = {
    "记忆调性": {
        "claim": "记忆是否有调性——记忆是否像音乐一样围绕一个中心组织。",
        "branches": [
            {
                "node": "记忆",
                "hook": "记忆不是被动的存档，而是过去以特定方式影响现在的过程。",
                "leaves": [
                    "时间在单向流逝，记忆只能面向已经发生过的事情。",
                    "事件是已经发生的事实，它们是记忆的原料。",
                    "正因为有因果——前一刻的状态决定了后一刻——记忆才能把过去与现在连起来。",
                    "记忆不是复制，而是塑造：它改造过去，使它成为现在的一部分。",
                    "当下是正在进行的那一刻，记忆总是在此刻被唤醒，而不是在过去。",
                ],
                "sentence": ("所谓记忆，是过去影响现在的方式：过去由已发生的事件构成（这些事件是记忆的原料），"
                             "它借因果之链把过去与现在连起来，并在每一次回想中被重新塑造；"
                             "而这一切总是发生在当下。"),
            },
            {
                "node": "调性",
                "hook": "调性是音乐中围绕一个主音来组织所有其他音的性质。",
                "leaves": [
                    "主音是中心的引力点，所有其他音都倾向于回到它。",
                    "音级衡量每个音相对主音的远近。",
                    "偏离是离开主音的张力，它制造不稳定。",
                    "回归是回到主音，它使张力得到释放。",
                ],
                "sentence": ("所谓调性，是围绕一个主音组织其他音：主音是中心的引力点，其他音都倾向回到它；"
                             "每个音有自己相对主音的远近（音级），离开主音就产生张力（偏离），"
                             "回到主音张力才释放（回归）。"),
            },
        ],
        "final": None,  # 下面填
    },
}

# 手工把 final 写好(把两个 branch 的句子织成段落)
TREE["记忆调性"]["final"] = (
    "记忆调性，若是一个真实概念，它说的是：记忆不是平铺的档案，而是像音乐一样围绕某些中心组织。"
    "所谓记忆，是过去影响现在的方式：过去由已发生的事件构成（这些事件是记忆的原料），"
    "它借因果之链把过去与现在连起来，并在每一次回想中被重新塑造，而这一切总是发生在当下。"
    "所谓调性，是围绕一个主音组织其他音：主音是中心的引力点，其他音都倾向回到它；"
    "每个音有自己相对主音的远近（音级），离开主音就产生张力（偏离），回到主音张力才释放（回归）。"
    "于是记忆调性研究的是：哪些经验必然成为记忆的'主音'，它们如何像引力点一样组织其余的记忆，"
    "以及当记忆偏离它的中心时，那种张力如何被释放。"
)


def main():
    print("=" * 100)
    print("句子化还原 —— 原子概念织成有语义的段落")
    print("=" * 100)
    for name, t in TREE.items():
        print(f"\n『{name}』")
        print(f"\n  叶子(原子概念):")
        for b in t["branches"]:
            for l in b["leaves"]:
                print(f"    · {l}")
        print(f"\n  逐层还原(句子):")
        for b in t["branches"]:
            print(f"    「{b['node']}」: {b['sentence']}")
        print(f"\n  最终段落:")
        print(f"    {t['final']}")

    (HERE / "out/demo/reconstruct_sent.json").write_text(
        json.dumps(TREE, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\n已存 out/demo/reconstruct_sent.json")


if __name__ == "__main__":
    main()
