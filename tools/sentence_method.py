def generate(name, data):
    print(f"\n{'='*80}")
    print(f"## 「{name}」")
    print(f"  ① 问: {data['q_what']}")
    print(f"  ② 拆实体:")
    for e in data["entities"]:
        print(f"     - {e['name']}")
    print(f"  ③ 再问:")
    for e in data["entities"]:
        print(f"     - {e['q']} -> {e['essence']}")
    print(f"  ④ 再拆:")
    for e in data["entities"]:
        print(f"     - {e['name']}: {' / '.join(e['sub'])}")
    print(f"  ⑤ 成段:")
    print(f"     {data['paragraph']}")


def main():
    print("=" * 100)
    print("造句方法 —— 问→拆→再问→再拆→成段")
    print("=" * 100)
    for name, data in METHOD.items():
        generate(name, data)
    (HERE / "out/demo/sentence_method.json").write_text(
        json.dumps(METHOD, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\n已存 out/demo/sentence_method.json ({len(METHOD)} 个按方法造句)")


if __name__ == "__main__":
    main()
